export type MiniWalletMessageKey = keyof typeof miniWalletMessages.en;
export type MiniT = (key: MiniWalletMessageKey, values?: Record<string, string>) => string;

export function normalizeMiniLocale(value: unknown): MiniLocale {
  const text = String(value ?? "").toLowerCase();
  if (text.startsWith("zh")) return "zh";
  if (text.startsWith("ru")) return "ru";
  if (text.startsWith("fa") || text.startsWith("per") || text.startsWith("prs")) return "fa";
  return "en";
}

export function createMiniT(locale: MiniLocale): MiniT {
  return (key, values) => {
    let message: string = miniWalletMessages[locale][key] ?? miniWalletMessages.en[key] ?? key;
    for (const [name, value] of Object.entries(values ?? {})) {
      message = message.replaceAll(`{${name}}`, value);
    }
    return message;
  };
}

export function isMiniRtl(locale: MiniLocale) {
  return MINI_LOCALE_DIR[locale] === "rtl";
}

export function technicalTextDirection() {
  return "ltr" as const;
}

export function networkLabelForMini(network: string | null | undefined, t: MiniT) {
  return network === "trc20-mainnet" ? t("tronMainnet") : t("tronNile");
}
